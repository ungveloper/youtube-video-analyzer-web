import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import ts from 'typescript';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
function load(file){
 const out=ts.transpileModule(read(file),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS},reportDiagnostics:true});
 assert.equal(out.diagnostics?.length||0,0,`${file} syntax`);
 const mod={exports:{}};
 Function('exports','module','require',out.outputText)(mod.exports,mod,()=>{throw Error('No dynamic dependency expected')});
 return mod.exports;
}
const {coverageWindows,hasLateAnchors,missingEvidenceWindows}=load('lib/temporal-coverage.ts');
assert.deepEqual(coverageWindows(202).map(w=>[w.from,w.to]),[[0,50],[50,101],[101,151],[151,202]]);
assert.deepEqual(coverageWindows(202).map(w=>w.label),['00:00–00:50','00:50–01:41','01:41–02:31','02:31–03:22']);
const source=[{id:'e1',startSeconds:0,endSeconds:10,kind:'audio',note:'처음 발언입니다.'},{id:'e2',startSeconds:114,endSeconds:130,kind:'audio',note:'중간에 나온 환자 사례를 실제로 설명하고 있습니다.'}];
assert.equal(hasLateAnchors(source,202),false);
assert.deepEqual(missingEvidenceWindows(source,202),['00:50–01:41','02:31–03:22']);
const tail=[{id:'e3',startSeconds:164,endSeconds:180,kind:'audio',note:'마지막에 혈관 상태 점검을 권고하고 마무리합니다.'}];
assert.equal(hasLateAnchors([...source,...tail],202),true);
const {mergeFocusedTail,focusedTailPrompt}=load('lib/server/evidence-pipeline.ts');
const first={evidence:source,claims:[{id:'c1',text:'원문 발언 하나입니다.',category:'도입',evidenceIds:['e1']}],transcript:[],exclusions:[]};
const latter={evidence:[{id:'late0',startSeconds:42,endSeconds:49,kind:'audio',note:'초반부 내용입니다.'},{id:'late1',startSeconds:164,endSeconds:173,kind:'audio',note:'다리 상태의 경고 징후를 말합니다.'}],claims:[{id:'l0',text:'초반 주장 한 개입니다.',category:'초반',evidenceIds:['late0']},{id:'l1',text:'보행 중의 경고 신호를 설명합니다.',category:'후반',evidenceIds:['late1']}],transcript:[],exclusions:[]};
const merged=mergeFocusedTail(first,latter,202);
assert.equal(merged.added,1);
assert.deepEqual(merged.source.claims.map(x=>x.id),['c1','tail-c-1']);
assert.deepEqual(merged.source.evidence.map(x=>x.id),['e1','e2','tail-e-1']);
assert.match(focusedTailPrompt(202),/02:01/);
const duplicate=mergeFocusedTail(merged.source,latter,202);
assert.equal(duplicate.added,0,'same follow-up may not duplicate claims');
const {appendUnreferencedEvidenceNotes}=load('lib/timeline-granularity.ts');
const restored=appendUnreferencedEvidenceNotes([{id:'t1',text:'상세하고 중요한 첫 구간 설명이 남아 있습니다.',evidenceIds:['e1']}],[...source,...tail]);
assert.equal(restored.length,3);
assert.equal(restored[0].text,'상세하고 중요한 첫 구간 설명이 남아 있습니다.');
assert.equal(restored[2].evidenceIds[0],'e3');
const ai=read('lib/server/ai.ts');
assert.match(ai,/pass:'tail-scan'/);
assert.match(ai,/!hasLateAnchors\(source.evidence/);
assert.match(ai,/source=merged.source/);
assert.match(ai,/appendUnreferencedEvidenceNotes\(/);
assert.match(ai,/processing:videoProcessing/);
const {resolveVideoProcessing}=load('lib/video-processing.ts');
assert.equal(resolveVideoProcessing(202,'gemini-3.8-flash'),'static');
assert.equal(resolveVideoProcessing(900,'gemini-3.8-flash'),'agentic');
const toast=read('components/ui/sonner.tsx');
assert.match(toast,/position="bottom-right"/);
assert.match(toast,/visibleToasts=\{5\}/);
assert.match(toast,/expand gap=\{12\}/);
console.log('PASS: Sonner 5 expanded bottom-right; temporal quarters; no synthetic end markers; tail merge and dedupe; no lost timeline prose; selectable static/agentic video after source inspection');
