import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source=fs.readFileSync(path.join(root,'lib/server/interaction-sse.ts'),'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS},reportDiagnostics:true});
assert.equal(compiled.diagnostics?.length??0,0);
const exportsValue={};
Function('exports',compiled.outputText)(exportsValue);
const {readInteractionSse}=exportsValue;
const encoder=new TextEncoder();
const sseResponse=(parts)=>new Response(new ReadableStream({start(controller){for(const part of parts)controller.enqueue(encoder.encode(part));controller.close();}}),{headers:{'content-type':'text/event-stream'}});
const entry=(kind,data)=>`event: ${kind}\ndata: ${JSON.stringify({event_type:kind,...data})}\n\n`;
const start=entry('step.start',{index:1,step:{type:'model_output',content:[{type:'text',text:'{"trans'}]}});
const delta=entry('step.delta',{index:1,delta:{type:'text',text:'cript":['}});
const delta2=entry('step.delta',{index:1,delta:{type:'text',text:'{"text":"가나다"}]}'}});
const thought=entry('step.start',{index:0,step:{type:'thought'}});
const ignored=entry('step.delta',{index:0,delta:{type:'thought',text:'PRIVATE'}});
const done=entry('interaction.completed',{interaction:{status:'completed',usage:{total_input_tokens:100,total_output_tokens:12}}});
const text=thought+ignored+start+delta+delta2+done;
const parts=[text.slice(0,11),text.slice(11,50),text.slice(50,90),text.slice(90)];
const result=await readInteractionSse(sseResponse(parts));
assert.equal(result.output,'{"transcript":[{"text":"가나다"}]}');
assert.equal(result.inputTokens,100);
assert.equal(result.outputTokens,12);
assert.equal(result.chunks,3);
assert.ok(result.firstTextMs>=0);
await assert.rejects(readInteractionSse(sseResponse([start+delta])),/완료 이벤트 없이 종료/);
const utf8Bytes=encoder.encode(start+delta+delta2+done);
let cut=0;for(let i=0;i<utf8Bytes.length-1;i++){if(utf8Bytes[i]===0xea){cut=i+1;break;}}
assert.ok(cut>0,'한국어 멀티바이트 샘플이 존재해야 합니다');
const splitResponse=new Response(new ReadableStream({start(controller){controller.enqueue(utf8Bytes.slice(0,cut));controller.enqueue(utf8Bytes.slice(cut));controller.close();}}),{headers:{'content-type':'text/event-stream'}});
assert.equal((await readInteractionSse(splitResponse)).output,'{\"transcript\":[{\"text\":\"가나다\"}]}');
await assert.rejects(readInteractionSse(sseResponse([entry('error',{error:{code:'UNAVAILABLE',message:'busy'}})])),/UNAVAILABLE/);
assert.match(fs.readFileSync(path.join(root,'lib/server/ai.ts'),'utf8'),/store:false,stream:streamed/);
assert.match(fs.readFileSync(path.join(root,'lib/server/ai.ts'),'utf8'),/readInteractionSse\(response\)/);
assert.doesNotMatch(fs.readFileSync(path.join(root,'lib/server/ai.ts'),'utf8'),/background:true[,{]/);
console.log('PASS: Gemini SSE partial JSON, split UTF-8 events, complete event, thought exclusion, failure handling, stateless single-request path');
