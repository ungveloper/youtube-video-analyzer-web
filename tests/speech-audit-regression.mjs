import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const read=f=>fs.readFileSync(f,'utf8');
const out=ts.transpileModule(read('lib/speech-audit.ts'),{fileName:'lib/speech-audit.ts',compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS},reportDiagnostics:true});
assert.equal(out.diagnostics?.length||0,0);
const lib={};Function('exports',out.outputText)(lib);
const l=(s,e,t)=>({id:`l-${s}`,startSeconds:s,endSeconds:e,text:t,translated:false});
const basic=[l(0,5,'안녕하세요 반갑습니다.'),l(6,13,'동맥경화가 발생하는 원인을 알아보겠습니다.'),l(15,20,'다리 혈관은 점점 좁아질 수 있습니다.'),l(25,31,'걷다가 다리에 통증이 나타날 수 있습니다.'),l(35,40,'말초동맥의 상태를 함께 확인하세요.'),l(65,70,'운동을 하다 보면 아플 수 있습니다.'),l(72,76,'쉬면 증상이 줄어들 수 있습니다.'),l(82,86,'혈관의 위치를 살펴보겠습니다.'),l(90,94,'다리에 혈액이 잘 공급되어야 합니다.'),l(96,100,'다양한 원인과 증상이 나타날 수 있습니다.')];
const gap=lib.chooseSpeechGapAudit(basic,202,8);
assert.deepEqual(gap,{from:40,to:65},'prefer observed large interior gap');
const merge=lib.mergeGapAuditedLines(basic,[l(49,53,'혈관이 좁아지는 새로운 실제 발언이 있습니다.'),l(65,69,'운동을 하다 보면 아플 수 있습니다.'),l(48,51,'안녕하세요 반갑습니다.'),l(150,152,'다른 곳의 발언입니다.')],gap,202);
assert.equal(merge.added,1);assert(merge.lines.some(x=>x.startSeconds===49));
const clock=lib.planSpeechClockAudit(basic,202);
assert(clock&&clock.from>=60&&clock.to-clock.from<=24);
const known=[l(65,68,'첫 번째로 확인하는 정확한 발언입니다.'),l(70,74,'두 번째로 확인하는 정확한 발언입니다.'),l(76,79,'세 번째로 확인하는 정확한 발언입니다.'),l(90,94,'확인 범위 밖에 있는 발언입니다.')];
const win={from:60,to:84};
const req=lib.makeSpeechClockAuditRequest('https://www.youtube.com/watch?v=aFmUl65-2-c',win,known);
assert.deepEqual(req[0].processing,{type:'static',start_offset:'60s',end_offset:'84s'});
const checked=lib.applySpeechClockAudit(known,{lines:[{startSeconds:2,endSeconds:5,text:known[0].text},{startSeconds:7,endSeconds:11,text:known[1].text}]},win,202);
assert.equal(checked.reason,'consistent_video_relisten');assert.equal(checked.corrections,3);assert.deepEqual(checked.lines.slice(0,3).map(x=>x.startSeconds),[62,67,73]);
assert.equal(checked.lines[0].text,known[0].text,'never rewrite words');
assert.equal(lib.applySpeechClockAudit(known,{lines:[{startSeconds:2,endSeconds:5,text:known[0].text}]},win,202).corrections,0,'one model quote cannot move time');
assert.equal(lib.applySpeechClockAudit(known,{lines:[{startSeconds:2,endSeconds:5,text:known[0].text},{startSeconds:10,endSeconds:13,text:known[1].text}]},win,202).corrections,0,'conflicting shifts cannot move time');
assert.equal(lib.applySpeechClockAudit(known,{lines:[{startSeconds:2,endSeconds:5,text:'이 영상에서는 듣지 못한 문장입니다.'},{startSeconds:7,endSeconds:11,text:known[1].text}]},win,202).corrections,0,'paraphrases cannot move time');
const cfg=read('next.config.ts'),ai=read('lib/server/ai.ts'),prompt=read('lib/speech-clip-pipeline.ts');
assert.match(cfg,/devIndicators:\s*false/);
assert.match(ai,/chooseSpeechGapAudit\(finalLines,video\.durationSeconds/);
assert.match(ai,/makeSpeechClockAuditRequest\(video\.url/);
assert.match(ai,/applySpeechClockAudit\(finalLines/);
assert.match(prompt,/문장 하나를 여러 줄로 쪼개지/);
console.log('PASS: Next.js dev indicator off; interior gap recovery bounded; 2 exact audio quote time anchors; uncertainty preserves original times');
