assert(s.includes("if(rest.some(outcome=>outcome.failure==='FREE_LIMIT'))break"),'Stop batching after quota error');
const ui=fs.readFileSync('app/api/analyze/route.ts','utf8');
assert(ui.includes("emit({type:'failed',code,message,requestId})"),'SSE must surface failure instead of completed output');
console.log('PASS: primary/optional/compose quota failures never become completed results; severe failed-core gap guarded; SSE failed event preserved');
