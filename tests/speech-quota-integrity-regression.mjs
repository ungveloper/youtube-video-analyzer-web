import assert from 'node:assert/strict';
import fs from 'node:fs';
const source=fs.readFileSync('lib/server/ai.ts','utf8');
const start=source.indexOf('async function speechFocusedAnalysis(');
const end=source.indexOf('\nexport async function analyzeVideo(',start);
assert(start>=0&&end>start,'Actual video transcription implementation');
const s=source.slice(start,end);
const first=s.indexOf('const quotaClips=outcomes.filter(o=>o.failure');
const initialMerge=s.indexOf('const merged=collectSpeechClipResults(outcomes,segments);');
assert(first>0&&first<initialMerge,'A primary 429 must fail BEFORE partial transcript merging');
assert(s.includes("event:'analysis.speech_quota_abort',requestId,phase:'primary_clips'"));
assert(s.includes("throw new ServiceError('FREE_LIMIT'"));
