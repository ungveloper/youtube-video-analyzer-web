import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=relative=>fs.readFileSync(path.join(root,relative),'utf8');
const source=read('lib/provider-retry.ts');
const compiled=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS},reportDiagnostics:true});
assert.equal(compiled.diagnostics?.length??0,0);
const runtimeExports={};
Function('exports',compiled.outputText)(runtimeExports);
const {remainingBasicAnalysisMs,hasBasic503RetryBudget,MIN_BASIC_503_RETRY_MS}=runtimeExports;
assert.equal(MIN_BASIC_503_RETRY_MS,15000);
assert.equal(remainingBasicAnalysisMs(90000,0),90000);
assert.equal(remainingBasicAnalysisMs(90000,32000),58000);
assert.equal(remainingBasicAnalysisMs(90000,120000),0);
assert.equal(remainingBasicAnalysisMs(NaN,0),0);
assert.equal(hasBasic503RetryBudget(90000,32500),true,'503 after 32.5s can be retried within 90s overall');
assert.equal(hasBasic503RetryBudget(90000,77000),false,'503 after 77s must not trigger hopeless retry');
const ui=read('components/analysis-workspace.tsx');
const route=read('app/api/analyze/route.ts');
const ai=read('lib/server/ai.ts');
assert.match(ui,/const retryOnBusy=false;/,'503 retries remain disabled in one-click mode');
assert.match(ui,/const segmentShortSpeech=false;/,'experimental multiple-video batching stays disabled');
assert.match(route,/body\.retryOnBusy === undefined \? false/);
assert.match(route,/body\.segmentShortSpeech===undefined \? false/);
assert.match(ai,/const basicDeadlineMs=Date\.now\(\)\+firstTimeoutMs/);
assert.match(ai,/timeoutMs:remainingMs/);
assert.match(ai,/hasBasic503RetryBudget\(basicDeadlineMs,Date\.now\(\)\)/);
assert.match(ai,/event:'analysis\.provider_timeout'/);
assert.match(ai,/video\.durationSeconds<300\?120000:150000/);
assert.match(ai,/event:'analysis\.standard_503_retry_skipped'/);
console.log('PASS: 3-clip and 503 retry disabled by default, shared streamed standard deadline, low-budget retry blocked, timeout stage logs');
