import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import ts from 'typescript';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const load=(file)=>{
  const input=fs.readFileSync(path.join(root,file),'utf8');
  const output=ts.transpileModule(input,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022},reportDiagnostics:true});
  assert.equal(output.diagnostics?.length||0,0);
  const mod={exports:{}};
  Function('exports','module','require',output.outputText)(mod.exports,mod,()=>{throw Error('Unexpected import')});
  return mod.exports;
};
const {assessTimelineTiming,timelineStartSeconds,parseTimelineTime}=load('lib/timeline-accuracy.ts');
const times=[0,4,13,19,35,41,46,50,55,60,104,108,118,122,133,148,154];
const evidence=times.map((s,i)=>({id:`ev${i}`,startSeconds:s,endSeconds:Math.min(202,s+3),kind:'audio'}));
const items=evidence.map((e,i)=>({id:`t${i}`,text:`발언 ${i}`,evidenceIds:[e.id]}));
const review=assessTimelineTiming(items,evidence,202);
assert.deepEqual(review.gaps,[{from:60,to:104,seconds:44}]);
assert.equal(review.lastStartSeconds,154);
assert.equal(review.lastEndSeconds,157);
assert.equal(review.hasSparseEnding,true);
assert.equal(parseTimelineTime('01:44',202),104);
assert.equal(parseTimelineTime('1:44',202),104);
assert.equal(parseTimelineTime('00:03:22',202),202);
assert.equal(parseTimelineTime('1:99',202),null);
assert.equal(parseTimelineTime('3:23',202),null);
assert.equal(parseTimelineTime('44',202),null);
assert.equal(parseTimelineTime('-1:23',202),null);
const fixed={...items[10],timeOverrideSeconds:64};
assert.equal(timelineStartSeconds(fixed,evidence),64);
assert.equal(assessTimelineTiming([...items.slice(0,10),fixed,...items.slice(11)],evidence,202).gaps.length,1,'manual edit must not generate synthetic adjacent timecodes');
const captions=evidence.map(e=>({...e,kind:'caption'}));
assert.equal(assessTimelineTiming(items,captions,202).lastStartSeconds,154,'caption timing stays unchanged');
const ui=fs.readFileSync(path.join(root,'components/detailed-analysis-list.tsx'),'utf8');
const workspace=fs.readFileSync(path.join(root,'components/analysis-workspace.tsx'),'utf8');
const exporters=fs.readFileSync(path.join(root,'lib/exporters.ts'),'utf8');
assert.match(ui,/AI 추정 시각/);
assert.match(ui,/시각 수정/);
assert.match(workspace,/parseTimelineTime/);
assert.match(workspace,/assessTimelineTiming/);
assert.match(exporters,/AI 추정 시각/);
console.log('PASS: no arbitrary timeline shifts; 44s silent anchor gap; truncated late anchors; source captions distinguished; manual MM:SS correction and export');
