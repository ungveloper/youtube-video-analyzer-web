import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
import { fileURLToPath } from 'node:url';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const source=fs.readFileSync(path.join(root,'lib/video-processing.ts'),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const exports={};
Function('exports',js)(exports);
const {resolveVideoProcessing,isVideoProcessingPreference,SHORT_VIDEO_SECONDS}=exports;
assert.equal(SHORT_VIDEO_SECONDS,300);
assert.equal(resolveVideoProcessing(202,'gemini-3.8-flash'),'static');
assert.equal(resolveVideoProcessing(299,'gemini-3.8-flash'),'static');
assert.equal(resolveVideoProcessing(300,'gemini-3.8-flash'),'agentic');
assert.equal(resolveVideoProcessing(900,'gemini-3.8-flash'),'agentic');
assert.equal(resolveVideoProcessing(900,'gemini-3.5-flash-lite'),'static');
assert.equal(resolveVideoProcessing(202,'gemini-3.8-flash','agentic'),'agentic');
assert.equal(resolveVideoProcessing(900,'gemini-3.8-flash','static'),'static');
assert.equal(isVideoProcessingPreference('auto'),true);
assert.equal(isVideoProcessingPreference('static'),true);
assert.equal(isVideoProcessingPreference('agentic'),true);
assert.equal(isVideoProcessingPreference('paid'),false);
assert.equal(isVideoProcessingPreference(null),false);
const ai=fs.readFileSync(path.join(root,'lib/server/ai.ts'),'utf8');
const route=fs.readFileSync(path.join(root,'app/api/analyze/route.ts'),'utf8');
const ui=fs.readFileSync(path.join(root,'components/analysis-workspace.tsx'),'utf8');
assert.match(ai,/const videoProcessing=resolveVideoProcessing/);
assert.match(ai,/thinkingLevel:'low',maxOutputTokens:video.durationSeconds<300\?12000:16000/);
assert.doesNotMatch(ai,/processing:'agentic' as const/);
assert.match(ai,/const attempts=\[video.durationSeconds<300\?90000:120000\]/);
assert.match(route,/analysis\.timing/);
assert.match(route,/isVideoProcessingPreference\(processingPreference\)/);
assert.match(ui,/<option value="static">Static/);
assert.match(ui,/<option value="agentic">Agentic/);
console.log('PASS: video processing auto/manual decisions, validation, logging and fast single-call invariants');
